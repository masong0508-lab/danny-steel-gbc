"""d_major_bossa_title_v6.mid -> 4-bar intro + loop, as a Game Boy Color sound event table (src/music_data.c)
Run: python3 tools/make_gbc_music.py
Same arrangement as the GBA build (tools/make_music.py); differences:
  * time base is 1/1024 s ticks (the timer interrupt fires at 1024 Hz), stored as u16
  * an event is {u16 t, u16 val, u8 ch, u8 arg} = 6 bytes
  * ch 0 lead (pulse 1) | 1 comp (pulse 2) | 2 bass (wave) | 3 percussion (noise), val = 11-bit frequency register value"""
import struct, sys
sys.path.insert(0, 'tools')
from midiparse import parse

SRC = 'assets/d_major_bossa_title_v6.mid'
PPQ, BAR = 480, 1920
INTRO, LOOP = 4 * BAR, 8 * BAR
TICKS_PER_MIDI_TICK = 1024.0 * 60.0 / 84.0 / 480.0          # 1/1024 s ticks per MIDI tick (84 bpm)

fmt, div, tr = parse(SRC)
assert div == PPQ

def notes_of(ti):
    on, out = {}, []
    for t, k, st, d in tr[ti]:
        if k != 'ch': continue
        c = st >> 4
        if c == 9 and d[1] > 0: on[d[0]] = (t, d[1])
        elif c == 8 or c == 9:
            t0, v = on.pop(d[0]); out.append((t0, t - t0, d[0], v))
    return sorted(out)

lead, comp, bass, perc = (notes_of(i) for i in (1, 2, 3, 4))
H = LOOP // 2
def cut(notes, a, b, shift):
    return [(t - a + shift, d, p, v) for (t, d, p, v) in notes if a <= t < b]
intro = {'lead': cut(lead, 6 * BAR, 8 * BAR, 2 * BAR), 'comp': cut(comp, H + BAR, 8 * BAR, BAR),
         'bass': cut(bass, H, 8 * BAR, 0), 'perc': cut(perc, H, 8 * BAR, 0)}
song = {k: [(t + INTRO, d, p, v) for (t, d, p, v) in n] for k, n in
        (('lead', lead), ('comp', comp), ('bass', bass), ('perc', perc))}
full = {k: sorted(intro[k] + song[k]) for k in intro}

# GB registers: freq = 2048 - 131072/f (pulse) or 2048 - 65536/f (wave) -- the same numbers the GBA used
def sq_rate(p): return int(round(2048 - 131072.0 / (440.0 * 2 ** ((p - 69) / 12.0))))
def wv_rate(p): return int(round(2048 - 65536.0 / (440.0 * 2 ** ((p - 69) / 12.0))))
def vol(v, mul=1.0): return max(1, min(15, int(round(v / 127.0 * 15 * mul))))
ev = []
def add(tick, ch, val, arg):
    assert 0 <= val <= 2047
    ev.append((int(round(tick * TICKS_PER_MIDI_TICK)), ch, val, arg))
def mono(ch, notes, rate, volf):
    for i, (t, d, p, v) in enumerate(notes):
        add(t, ch, rate(p), volf(v))
        nxt = notes[i + 1][0] if i + 1 < len(notes) else None
        if nxt is None or nxt - (t + d) > 3: add(t + d, ch, 0, 0)
mono(0, full['lead'], sq_rate, lambda v: vol(v, 1.15))
mono(1, full['comp'], sq_rate, lambda v: vol(v, 1.1))
mono(2, full['bass'], wv_rate, lambda v: 1)
for t, d, p, v in full['perc']:
    add(t, 3, 0, vol(v, 1.3) | ((1 if p == 42 else 2) << 4))
ev.sort(key=lambda e: (e[0], e[3] != 0 if e[1] < 3 else 1))
loop_idx = next(i for i, e in enumerate(ev) if e[0] >= INTRO * TICKS_PER_MIDI_TICK - 0.5)
loop_ticks = int(round(LOOP * TICKS_PER_MIDI_TICK))
assert ev[-1][0] < 65535
with open('src/music_data.c', 'w') as o:
    o.write('// GENERATED by tools/make_gbc_music.py - do not edit\n#include "data.h"\n')
    o.write('const unsigned int MUSIC_COUNT = %d;\nconst unsigned int MUSIC_LOOP_IDX = %d;\nconst unsigned int MUSIC_LOOP_TICKS = %d;\n' % (len(ev), loop_idx, loop_ticks))
    o.write('const MusEv music_events[%d] = {\n' % len(ev))
    for i in range(0, len(ev), 4):
        o.write(' '.join('{%d,%d,%d,%d},' % (e[0], e[2], e[1], e[3]) for e in ev[i:i + 4]) + '\n')
    o.write('};\n')
print('events', len(ev), '(%d bytes)' % (6 * len(ev)), 'loop starts at event', loop_idx, 'loop ticks', loop_ticks,
      'intro %.2f s, loop %.2f s, last event %.2f s' % (INTRO * TICKS_PER_MIDI_TICK / 1024, loop_ticks / 1024, ev[-1][0] / 1024))
